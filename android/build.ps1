param(
    [ValidateSet('arm64-v8a','armeabi-v7a')]
    [string]$Architecture = 'arm64-v8a',
    [string]$XrayArchive = '',
    [string]$XrayCore = '',
    [string]$XrayLicense = '',
    [string]$SigningAlias = 'wayline',
    [string]$Ndk = '',
    [string]$SigningKey = (Join-Path $env:LOCALAPPDATA 'Wayline/signing/local.p12'),
    [string]$ToolRoot = (Join-Path $PSScriptRoot '..\..\android-tools'),
    [string]$Jdk = 'C:\Program Files\Java\jdk-22',
    [string]$EnginePath = '',
    [string]$Go = 'go'
)
$ErrorActionPreference = 'Stop'
$ToolRoot = [System.IO.Path]::GetFullPath($ToolRoot)
$buildTools = Join-Path $ToolRoot 'build-tools\android-16'
$platformJar = Join-Path $ToolRoot 'platform\android-36\android.jar'
if (-not (Test-Path -LiteralPath $platformJar)) { $platformJar = Join-Path $ToolRoot 'platforms/android-36/android.jar' }
if (-not (Test-Path -LiteralPath $buildTools)) { $buildTools = Join-Path $ToolRoot 'build-tools/36.0.0' }
$build = Join-Path $PSScriptRoot "build/$Architecture"
$manifest = [xml](Get-Content -LiteralPath (Join-Path $PSScriptRoot 'AndroidManifest.xml') -Raw)
$releaseVersion = $manifest.manifest.GetAttribute('versionName', 'http://schemas.android.com/apk/res/android')
$releaseCode = $manifest.manifest.GetAttribute('versionCode', 'http://schemas.android.com/apk/res/android')
if ($releaseVersion -notmatch '^\d+\.\d+\.\d+$') { throw 'Invalid Android release version' }
$classes = Join-Path $build 'classes'
$dex = Join-Path $build 'dex'
$signing = Split-Path -Parent $SigningKey
New-Item -ItemType Directory -Force -Path $build,$classes,$dex,$signing | Out-Null
# Remove only generated bytecode directories inside this build directory.
$resolvedBuild = [System.IO.Path]::GetFullPath($build).TrimEnd('\','/') + [System.IO.Path]::DirectorySeparatorChar
foreach ($generated in @($classes,$dex)) {
    $resolvedGenerated = [System.IO.Path]::GetFullPath($generated)
    if (-not $resolvedGenerated.StartsWith($resolvedBuild,[System.StringComparison]::OrdinalIgnoreCase)) {
        throw 'Generated bytecode path escaped the Android build directory'
    }
    Remove-Item -LiteralPath $resolvedGenerated -Recurse -Force
    New-Item -ItemType Directory -Path $resolvedGenerated | Out-Null
}
function CheckExit([string]$step) { if ($LASTEXITCODE -ne 0) { throw "$step failed with exit code $LASTEXITCODE" } }
$staging = Join-Path $PSScriptRoot 'staging'
$nativeDir = Join-Path $staging "lib/$Architecture"
New-Item -ItemType Directory -Force -Path $nativeDir | Out-Null
$stagedEngine = Join-Path $nativeDir 'libwayline.so'
if ($EnginePath) {
    Copy-Item -LiteralPath $EnginePath -Destination $stagedEngine -Force
} else {
    $oldGoOs = $env:GOOS
    $oldGoArch = $env:GOARCH
    $oldCgo = $env:CGO_ENABLED
    $oldCc = $env:CC
    $oldArm = $env:GOARM
    try {
        $env:GOOS = 'android'
        $env:GOARCH = 'arm64'
        $env:CGO_ENABLED = '0'
        if ($Architecture -eq 'armeabi-v7a') {
            if (-not $Ndk) { throw 'ARMv7 needs -Ndk pointing to the LLVM prebuilt toolchain directory' }
            $env:GOARCH = 'arm'
            $env:GOARM = '7'
            $env:CGO_ENABLED = '1'
            $env:CC = '"' + (Join-Path $Ndk 'bin/clang.exe') + '" --target=armv7a-linux-androideabi26 -mfpu=vfpv3-d16 "--sysroot=' + (Join-Path $Ndk 'sysroot') + '"'
        }
        & $Go -C (Join-Path $PSScriptRoot '..\engine') build -buildvcs=false -trimpath -ldflags '-s -w -extldflags=-Wl,-z,max-page-size=16384' -o $stagedEngine .
        CheckExit 'Go Android engine build'
    } finally {
        $env:GOOS = $oldGoOs
        $env:GOARCH = $oldGoArch
        $env:CGO_ENABLED = $oldCgo
        $env:CC = $oldCc
        $env:GOARM = $oldArm
    }
}
$sources = @(Get-ChildItem -Recurse -LiteralPath (Join-Path $PSScriptRoot 'src') -Filter '*.java' | ForEach-Object FullName)
& "$Jdk\bin\javac.exe" -encoding UTF-8 --release 8 -classpath $platformJar -d $classes @sources
CheckExit 'javac'
& "$Jdk\bin\jar.exe" cf (Join-Path $build 'classes.jar') -C $classes .
CheckExit 'jar'
& "$Jdk\bin\java.exe" -cp "$buildTools\lib\d8.jar" com.android.tools.r8.D8 --min-api 26 --lib $platformJar --output $dex (Join-Path $build 'classes.jar')
CheckExit 'd8'
& "$buildTools\aapt2.exe" compile --dir (Join-Path $PSScriptRoot 'res') -o (Join-Path $build 'resources.zip')
CheckExit 'aapt2 resources'
& "$buildTools\aapt2.exe" link -o (Join-Path $build 'base.apk') -I $platformJar --manifest (Join-Path $PSScriptRoot 'AndroidManifest.xml') --min-sdk-version 26 --target-sdk-version 36 (Join-Path $build 'resources.zip')
CheckExit 'aapt2'
$env:WAYLINE_ANDROID_BUILD = $build
$env:WAYLINE_ANDROID_STAGING = $staging
$env:WAYLINE_ANDROID_ARCH = $Architecture
$env:WAYLINE_ANDROID_XRAY = $XrayArchive
$env:WAYLINE_ANDROID_XRAY_CORE = $XrayCore
$env:WAYLINE_ANDROID_XRAY_LICENSE = $XrayLicense
@'
import hashlib, os, pathlib, zipfile
build=pathlib.Path(os.environ['WAYLINE_ANDROID_BUILD'])
staging=pathlib.Path(os.environ['WAYLINE_ANDROID_STAGING'])
arch=os.environ['WAYLINE_ANDROID_ARCH']
engine=staging/f'lib/{arch}/libwayline.so'
if not engine.is_file(): raise SystemExit('Missing native engine: '+str(engine))
core=os.environ['WAYLINE_ANDROID_XRAY_CORE']
if core:
    xray=pathlib.Path(core).read_bytes()
    license_text=pathlib.Path(os.environ['WAYLINE_ANDROID_XRAY_LICENSE']).read_bytes()
else:
    archive=pathlib.Path(os.environ['WAYLINE_ANDROID_XRAY'])
    if arch!='arm64-v8a' or hashlib.sha256(archive.read_bytes()).hexdigest()!='edcefc25b9b3195b11e18624c8269a969d6aabc39c6298a9a5ab29de15d46f3b':
        raise SystemExit('Expected the pinned official Xray v26.11.9 ARM64 ZIP or a source-built ARMv7 core')
    with zipfile.ZipFile(archive) as source:
        xray=source.read('xray')
        license_text=source.read('LICENSE')
import struct
expected={'arm64-v8a':(2,183),'armeabi-v7a':(1,40)}[arch]
for payload in [engine.read_bytes(),xray]:
    if payload[:4]!=b'\x7fELF' or payload[4]!=expected[0] or struct.unpack_from('<H',payload,18)[0]!=expected[1] or struct.unpack_from('<H',payload,16)[0]!=3:
        raise SystemExit('Native binary target is not a PIE for '+arch)
with zipfile.ZipFile(build/'base.apk') as source, zipfile.ZipFile(build/'unsigned.apk','w',compression=zipfile.ZIP_DEFLATED) as output:
    for entry in source.infolist(): output.writestr(entry,source.read(entry.filename))
    for dex in sorted((build/'dex').glob('*.dex')): output.write(dex,dex.name)
    output.write(engine,f'lib/{arch}/libwayline.so')
    output.writestr(f'lib/{arch}/libxray.so',xray)
    project=staging.parent.parent
    output.write(project/'LICENSE','assets/licenses/Wayline-GPL-3.0.txt')
    output.write(project/'THIRD_PARTY_NOTICES.md','assets/licenses/THIRD_PARTY_NOTICES.md')
    output.writestr('assets/licenses/Wayline-SOURCE.txt','Corresponding source accompanies the Wayline 0.5.0 release as Wayline-0.5.0-source.zip. Build instructions: BUILDING.md.\n')
    output.writestr('assets/licenses/Xray-LICENSE.txt',license_text)
    output.writestr('assets/licenses/Xray-NOTICE.txt','Xray-core v26.11.9, MPL 2.0. Corresponding source: https://github.com/XTLS/Xray-core/tree/v26.11.9\n')
'@ | python -
CheckExit 'APK packaging'
& "$buildTools\zipalign.exe" -P 16 -f 4 (Join-Path $build 'unsigned.apk') (Join-Path $build 'aligned.apk')
CheckExit 'zipalign'
$key = $SigningKey
if (-not $env:WAYLINE_SIGNING_PASSWORD) { $env:WAYLINE_SIGNING_PASSWORD = 'wayline-local-debug' }
if (-not (Test-Path -LiteralPath $key)) {
    & "$Jdk\bin\keytool.exe" -genkeypair -keystore $key -storetype PKCS12 -storepass:env WAYLINE_SIGNING_PASSWORD -keypass:env WAYLINE_SIGNING_PASSWORD -alias $SigningAlias -keyalg RSA -keysize 2048 -validity 3650 -dname 'CN=Wayline Local Development'
    CheckExit 'keytool'
}
$apk = Join-Path $build "Wayline-$releaseVersion-$Architecture.apk"
& "$Jdk\bin\java.exe" -jar "$buildTools\lib\apksigner.jar" sign --ks $key --ks-pass env:WAYLINE_SIGNING_PASSWORD --key-pass env:WAYLINE_SIGNING_PASSWORD --ks-key-alias $SigningAlias --out $apk (Join-Path $build 'aligned.apk')
CheckExit 'apksigner sign'
& "$Jdk\bin\java.exe" -jar "$buildTools\lib\apksigner.jar" verify --verbose $apk
CheckExit 'apksigner verify'
& "$buildTools\zipalign.exe" -c -P 16 4 $apk
CheckExit 'zipalign verify'
$release = @{
    architecture = $Architecture
    version = $releaseVersion
    versionCode = [int]$releaseCode
    apk = [System.IO.Path]::GetFileName($apk)
    sha256 = (Get-FileHash -Algorithm SHA256 -LiteralPath $apk).Hash.ToLowerInvariant()
    engineSha256 = (Get-FileHash -Algorithm SHA256 -LiteralPath $stagedEngine).Hash.ToLowerInvariant()
    dexSha256 = (Get-FileHash -Algorithm SHA256 -LiteralPath (Join-Path $dex 'classes.dex')).Hash.ToLowerInvariant()
}
$release | ConvertTo-Json | Set-Content -LiteralPath (Join-Path $build 'release.json') -Encoding utf8
Get-Item -LiteralPath $apk | Select-Object FullName,Length
Get-FileHash -Algorithm SHA256 -LiteralPath $apk
